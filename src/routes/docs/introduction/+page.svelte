		</p>
		<ul>
			<li>streaming output from LLMs and other live sources</li>
			<li>
				authoring with Svelte components, with an optional build-time preprocessor that compiles
				static usage to plain Svelte markup
			</li>
			<li>
				rendering TSDoc/JSDoc comments on docs websites with domain-specific behavior like
				backticked identifiers linkifying to API docs
			</li>
			<li>dynamic content from untrusted users, with granular control over enabled behaviors</li>
		</ul>
		<p>
			mdz's predictable grammar means streaming never re-parses: LLM output renders incrementally,
			and the infrequent corrections -- like an unclosed <code>**</code> or a link resolving late --
			are bounded, explicit opcodes. The streaming design is derived from
			<a href="https://github.com/pngwn">@pngwn</a>'s ideas in this
			<a href="https://bsky.app/profile/pngwn.at/post/3mi527zntb22n">Bluesky thread</a>
