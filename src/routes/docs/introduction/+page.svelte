			pngwn's <a href="https://mdsvex.pngwn.io/">MDsveX</a>.
		</p>
		<p>
			mdz takes after <a href="https://commonmark.org/">CommonMark</a> and
			<a href="https://github.github.com/gfm/">GFM</a>, diverging where their rules fight streaming
